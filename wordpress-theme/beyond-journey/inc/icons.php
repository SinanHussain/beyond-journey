/** Social networks shown in the footer, in order, with their display names. */
function bj_social_networks() {
	return array(
		'facebook'  => 'Facebook',
		'x'         => 'X',
		'linkedin'  => 'LinkedIn',
		'instagram' => 'Instagram',
		'tiktok'    => 'TikTok',
	);
}

/**
 * "Follow us" row of social icons (only the networks with a link set). Prints nothing when none is set.
 *
 * @param string $label Text before the icons.
 */
function bj_social_row( $label ) {
	$links = '';
	foreach ( bj_social_networks() as $network => $name ) {
		$url = bj_setting( $network );
		if ( $url ) {
			/* translators: %s: social network. */
			$links .= '<a href="' . esc_url( $url ) . '" target="_blank" rel="noopener noreferrer" aria-label="' . esc_attr( sprintf( __( 'Beyond Journey Tourism on %s', 'beyond-journey' ), $name ) ) . '">' . bj_social_svg( $network, 'h-4 w-4' ) . '</a>';
		}
	}
	if ( '' !== $links ) {
		echo '<div class="contact-social"><span class="contact-social-label">' . esc_html( $label ) . '</span>' . $links . '</div>'; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped above.
	}
}
